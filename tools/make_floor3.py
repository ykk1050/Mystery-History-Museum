def patch_of(p):
    k = p[0]
    if k == 'L': return {'lines': {str(p[1]): p[2]}}
    if k == 'M': return {'lines': p[1]}
    if k == 'T': return {'tag': p[1]}
    if k == 'N': return {'title': p[1]}
    if k == 'S': return {'speech': p[1]}
    raise ValueError(k)
TYPE = {'L': '설명 문장', 'M': '설명 문장', 'T': '시대·나라 표시', 'N': '이름', 'S': '해설사 말'}

def build():
    rooms, review, md = [], [], []
    total = 0
    for n, r in enumerate(ROOMS, 1):
        ex = dict(r['ex']); ex['docent'] = dict(kind='docent', speech=r['speech'])
        an, items = [], []
        for i, (t, p, w, ri, pg, key) in enumerate(r['rows'], 1):
            assert t in ex, (r['id'], t)
            if p[0] in 'LM':
                for k in ([str(p[1])] if p[0] == 'L' else p[1].keys()):
                    assert int(k) < len(ex[t]['lines']), (r['id'], t, k)
            an.append([f'a{i:02d}', t, patch_of(p), w, ri])
            title = '해설사' if t == 'docent' else ex[t]['title']
            items.append(dict(id=f'r{n}-{i:02d}', n=i, ex=title, key=key, type=TYPE[p[0]], wrong=w, right=ri, page=pg))
        total += len(an)
        room = dict(id=r['id'], name=r['name'], wall=r['wall'], exhibits=ex, anomalies=an)
        if r.get('noChase'): room['noChase'] = True
        rooms.append(room)
        review.append(dict(name=r['name'], pages=r['pages'], items=items))
    return rooms, review, total

