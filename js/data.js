/* 정상 전시물에 이상 현상 패치를 적용한 사본을 돌려준다 */
window.applyPatch = function (base, patch) {
  const ex = JSON.parse(JSON.stringify(base));
  if (!patch) return ex;
  ['title', 'tag', 'sub', 'speech'].forEach(k => { if (patch[k] !== undefined) ex[k] = patch[k]; });
  if (patch.lines) Object.keys(patch.lines).forEach(i => { ex.lines[i] = patch.lines[i]; });
  if (patch.steps) Object.keys(patch.steps).forEach(i => { ex.steps[i] = patch.steps[i]; });
  ex.visual = Object.assign({}, ex.visual || {}, patch.visual || {});
  return ex;
};
